/// <summary>
/// 기체가 굴러가는 데 쓰는 자원. 최대값은 AgentStatus가, 현재값은 VitalStatus가 들고 간다.
/// 체력은 여기 들어가지 않는다 — 체력만 방어력·저항 계산을 타기 때문이다.
///
/// 배열 인덱스로 쓰이므로 0부터 빈틈없이 이어져야 한다. 뒤에만 추가할 것.
/// </summary>
public enum VitalType
{
    /// <summary>
    /// 전력. 무기 발사·실드 같은 기체 기능이 쓰고, 제너레이터가 시간이 지나면 채운다.
    /// 바닥나면 일정 비율까지 차야 다시 쓸 수 있다.
    /// </summary>
    Power = 0,

    /// <summary>
    /// 연료. 부스터와 이동이 쓴다. <b>스스로 차지 않는다</b> — 보급으로만 채운다.
    /// 바닥나면 기체가 기어다니고 손상이 누적된다.
    /// </summary>
    Fuel,
}

/// <summary>
/// 탄약 대분류(구경). 무기와 탄약이 서로 맞는지 판정하는 유일한 키다.
///
/// 같은 구경 안에서의 성능 차이(철갑탄/소이탄/고폭탄)는 여기가 아니라
/// <see cref="AmmoDataSO"/>가 스탯 변화량으로 표현한다.
/// 구경은 "끼워지는가", 탄종은 "얼마나 잘 나가는가"다. 섞지 말 것.
///
/// 새 구경은 <b>뒤에만</b> 추가한다. 이미 저장된 무기·탄약 에셋이 밀린다.
/// </summary>
public enum AmmoCaliberType
{
    None = 0,

    Small,          // 권총탄 - 가장 흔하고 약하다
    Middle,    // 소총탄(경) - 준수한 수준의 피해량과 장갑 관통력
    Heavy,          // 소총탄(중) - 높은 장갑 관통력
    Buckshot,      // 산탄 - 한 발이 여러 투사체로 갈라진다
    Grenade,      // 유탄 - 폭발 반경을 기본으로 갖는다
    Rocket,         // 로켓 - 느리고 크게 터진다
    EnergyCell,     // 에너지 셀 - 탄속이 빠르고 관통한다
}
